//! Plan `clipboard-safety`: the clipboard as a whole, so Typelite can put back exactly what the
//! user had.
//!
//! On macOS the clipboard is the general `NSPasteboard`. It holds items (one per copied thing),
//! and each item holds the same content in several types: plain text, rich text, HTML, an image,
//! a file URL. A [`Snapshot`] keeps every type of every item, so an image, a file or formatted
//! text comes back unchanged; reading only the plain text (as before) lost them.
//!
//! The pasteboard also has a change count that goes up with every write by any app. Typelite
//! uses it to tell whether the clipboard still holds what it wrote, and whether an app answered
//! a ⌘C, without comparing contents.
//!
//! Text Typelite puts there only for a moment (to paste it) is marked with the
//! `org.nspasteboard.TransientType` and `org.nspasteboard.AutoGeneratedType` types from
//! nspasteboard.org, which clipboard managers (Maccy, Paste, Raycast, Alfred) skip, so a
//! dictation does not show up in their history.
//!
//! Outside macOS the snapshot is the plain text only, as before.

/// Everything that was on the clipboard.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Snapshot(platform::Snapshot);

impl Snapshot {
    /// Number of items (0 for an empty clipboard), for logs.
    pub fn item_count(&self) -> usize {
        self.0.item_count()
    }
}

/// Copies the whole clipboard. `None` when it cannot be read.
pub fn snapshot() -> Option<Snapshot> {
    platform::snapshot(&platform::general()?).map(Snapshot)
}

/// Puts a snapshot back (an empty one empties the clipboard). True when it was written.
pub fn restore(snapshot: &Snapshot) -> bool {
    platform::general().is_some_and(|board| platform::restore(&board, &snapshot.0))
}

/// A number that changes whenever anything writes the clipboard.
pub fn change_count() -> Option<i64> {
    platform::general().map(|board| platform::change_count(&board))
}

/// Replaces the clipboard with `text`, marked as transient so clipboard managers skip it.
/// Returns the change count after the write, to check later that the clipboard still holds it.
pub fn write_transient_text(text: &str) -> Option<i64> {
    let board = platform::general()?;
    platform::write_text(&board, text, true).then(|| platform::change_count(&board))
}

/// Replaces the clipboard with `text` as a normal copy (the user asked for it, so it stays).
pub fn write_text(text: &str) -> bool {
    platform::general().is_some_and(|board| platform::write_text(&board, text, false))
}

/// A snapshot holding one plain text item, for tests.
#[cfg(test)]
pub fn text_snapshot(text: &str) -> Snapshot {
    Snapshot(platform::text_snapshot(text))
}

/// The clipboard's plain text, if it has any.
pub fn read_text() -> Option<String> {
    platform::read_text(&platform::general()?)
}

#[cfg(target_os = "macos")]
mod platform {
    //! Raw calls into AppKit's `NSPasteboard` through the Objective-C runtime (`objc2`). Every
    //! object here is autoreleased or released before the function returns.

    use objc2::rc::autoreleasepool;
    use objc2::runtime::{AnyObject, Bool};
    use objc2::{class, msg_send};
    use std::ffi::{c_char, c_void, CStr};

    /// `NSUTF8StringEncoding`.
    const UTF8: usize = 4;
    /// Uniform type of plain UTF-8 text (`NSPasteboardTypeString`).
    const TEXT_TYPE: &str = "public.utf8-plain-text";
    /// nspasteboard.org markers: the content is about to be replaced, and an app (not the user)
    /// put it there. Clipboard managers do not record such content.
    const TRANSIENT_TYPES: [&str; 2] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ];

    /// One item: each type with its data.
    pub type Item = Vec<(String, Vec<u8>)>;

    #[derive(Debug, Clone, PartialEq, Eq)]
    pub struct Snapshot {
        items: Vec<Item>,
    }

    impl Snapshot {
        pub fn item_count(&self) -> usize {
            self.items.len()
        }
    }

    /// A pasteboard: the general one, or (tests) a private one that is released on drop.
    pub struct Board {
        ptr: *mut AnyObject,
        owned: bool,
    }

    impl Drop for Board {
        fn drop(&mut self) {
            if self.owned {
                unsafe {
                    let _: () = msg_send![self.ptr, releaseGlobally];
                }
            }
        }
    }

    pub fn general() -> Option<Board> {
        let ptr: *mut AnyObject = unsafe { msg_send![class!(NSPasteboard), generalPasteboard] };
        (!ptr.is_null()).then_some(Board { ptr, owned: false })
    }

    /// A new private pasteboard, for tests: the user's clipboard is never touched.
    #[cfg(test)]
    pub fn private() -> Board {
        let ptr: *mut AnyObject =
            unsafe { msg_send![class!(NSPasteboard), pasteboardWithUniqueName] };
        assert!(!ptr.is_null());
        Board { ptr, owned: true }
    }

    unsafe fn ns_string(text: &str) -> *mut AnyObject {
        let string: *mut AnyObject = msg_send![class!(NSString), alloc];
        let string: *mut AnyObject = msg_send![
            string,
            initWithBytes: text.as_ptr() as *const c_void,
            length: text.len(),
            encoding: UTF8
        ];
        // Owned (+1); hand it to the pool so callers need not release it.
        msg_send![string, autorelease]
    }

    unsafe fn rust_string(string: *mut AnyObject) -> Option<String> {
        if string.is_null() {
            return None;
        }
        let utf8: *const c_char = msg_send![string, UTF8String];
        (!utf8.is_null()).then(|| CStr::from_ptr(utf8).to_string_lossy().into_owned())
    }

    unsafe fn ns_data(bytes: &[u8]) -> *mut AnyObject {
        msg_send![
            class!(NSData),
            dataWithBytes: bytes.as_ptr() as *const c_void,
            length: bytes.len()
        ]
    }

    unsafe fn rust_bytes(data: *mut AnyObject) -> Option<Vec<u8>> {
        if data.is_null() {
            return None;
        }
        let length: usize = msg_send![data, length];
        let bytes: *const c_void = msg_send![data, bytes];
        if length == 0 || bytes.is_null() {
            return Some(Vec::new());
        }
        Some(std::slice::from_raw_parts(bytes as *const u8, length).to_vec())
    }

    pub fn change_count(board: &Board) -> i64 {
        let count: isize = unsafe { msg_send![board.ptr, changeCount] };
        count as i64
    }

    pub fn snapshot(board: &Board) -> Option<Snapshot> {
        autoreleasepool(|_| unsafe {
            let items: *mut AnyObject = msg_send![board.ptr, pasteboardItems];
            if items.is_null() {
                return Some(Snapshot { items: Vec::new() });
            }
            let count: usize = msg_send![items, count];
            let mut saved = Vec::with_capacity(count);
            for index in 0..count {
                let item: *mut AnyObject = msg_send![items, objectAtIndex: index];
                let types: *mut AnyObject = msg_send![item, types];
                let type_count: usize = if types.is_null() {
                    0
                } else {
                    msg_send![types, count]
                };
                let mut entries = Vec::with_capacity(type_count);
                for type_index in 0..type_count {
                    let pasteboard_type: *mut AnyObject =
                        msg_send![types, objectAtIndex: type_index];
                    let data: *mut AnyObject = msg_send![item, dataForType: pasteboard_type];
                    if let (Some(name), Some(bytes)) =
                        (rust_string(pasteboard_type), rust_bytes(data))
                    {
                        entries.push((name, bytes));
                    }
                }
                saved.push(entries);
            }
            Some(Snapshot { items: saved })
        })
    }

    /// Clears the pasteboard and writes `items` (none: it stays empty).
    unsafe fn write_items(board: &Board, items: &[Item]) -> bool {
        let _: isize = msg_send![board.ptr, clearContents];
        if items.is_empty() {
            return true;
        }
        let array: *mut AnyObject = msg_send![class!(NSMutableArray), array];
        for entries in items {
            let item: *mut AnyObject = msg_send![class!(NSPasteboardItem), new];
            for (name, bytes) in entries {
                let _: Bool = msg_send![item, setData: ns_data(bytes), forType: ns_string(name)];
            }
            let _: () = msg_send![array, addObject: item];
            let _: () = msg_send![item, release];
        }
        let written: Bool = msg_send![board.ptr, writeObjects: array];
        written.as_bool()
    }

    pub fn restore(board: &Board, snapshot: &Snapshot) -> bool {
        autoreleasepool(|_| unsafe { write_items(board, &snapshot.items) })
    }

    pub fn write_text(board: &Board, text: &str, transient: bool) -> bool {
        let mut item: Item = vec![(TEXT_TYPE.to_string(), text.as_bytes().to_vec())];
        if transient {
            item.extend(TRANSIENT_TYPES.map(|name| (name.to_string(), Vec::new())));
        }
        autoreleasepool(|_| unsafe { write_items(board, &[item]) })
    }

    pub fn read_text(board: &Board) -> Option<String> {
        autoreleasepool(|_| unsafe {
            let text: *mut AnyObject = msg_send![board.ptr, stringForType: ns_string(TEXT_TYPE)];
            rust_string(text)
        })
    }

    /// The types of the first item, for tests.
    #[cfg(test)]
    pub fn first_item_types(board: &Board) -> Vec<String> {
        snapshot(board)
            .and_then(|snapshot| snapshot.items.into_iter().next())
            .map(|item| item.into_iter().map(|(name, _)| name).collect())
            .unwrap_or_default()
    }

    #[cfg(test)]
    pub fn snapshot_of(items: Vec<Item>) -> Snapshot {
        Snapshot { items }
    }

    #[cfg(test)]
    pub fn text_snapshot(text: &str) -> Snapshot {
        snapshot_of(vec![vec![(
            TEXT_TYPE.to_string(),
            text.as_bytes().to_vec(),
        )]])
    }
}

#[cfg(not(target_os = "macos"))]
mod platform {
    //! Outside macOS only the plain text is kept, through `arboard` (as before plan
    //! `clipboard-safety`); the change count is emulated from the text.

    #[derive(Debug, Clone, PartialEq, Eq)]
    pub struct Snapshot {
        text: Option<String>,
    }

    impl Snapshot {
        pub fn item_count(&self) -> usize {
            usize::from(self.text.is_some())
        }
    }

    pub struct Board;

    pub fn general() -> Option<Board> {
        Some(Board)
    }

    pub fn change_count(_board: &Board) -> i64 {
        use std::hash::{Hash, Hasher};
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        read_text(&Board).hash(&mut hasher);
        hasher.finish() as i64
    }

    pub fn snapshot(_board: &Board) -> Option<Snapshot> {
        let mut clipboard = arboard::Clipboard::new().ok()?;
        Some(Snapshot {
            text: clipboard.get_text().ok(),
        })
    }

    pub fn restore(_board: &Board, snapshot: &Snapshot) -> bool {
        let Ok(mut clipboard) = arboard::Clipboard::new() else {
            return false;
        };
        match &snapshot.text {
            Some(text) => clipboard.set_text(text.clone()).is_ok(),
            None => clipboard.clear().is_ok(),
        }
    }

    pub fn write_text(_board: &Board, text: &str, _transient: bool) -> bool {
        arboard::Clipboard::new()
            .and_then(|mut clipboard| clipboard.set_text(text.to_string()))
            .is_ok()
    }

    pub fn read_text(_board: &Board) -> Option<String> {
        arboard::Clipboard::new().ok()?.get_text().ok()
    }

    #[cfg(test)]
    pub fn text_snapshot(text: &str) -> Snapshot {
        Snapshot {
            text: Some(text.to_string()),
        }
    }
}

#[cfg(all(test, target_os = "macos"))]
mod tests {
    use super::platform;

    #[test]
    fn a_snapshot_brings_back_every_item_and_type_exactly() {
        let board = platform::private();
        // Formatted text plus plain text in one item, and an image-like second item.
        let original = platform::snapshot_of(vec![
            vec![
                ("public.rtf".to_string(), b"{\\rtf1 bold}".to_vec()),
                (
                    "public.utf8-plain-text".to_string(),
                    "粗體 bold".as_bytes().to_vec(),
                ),
            ],
            vec![(
                "public.png".to_string(),
                vec![0x89, b'P', b'N', b'G', 0, 1, 2, 255],
            )],
        ]);
        assert!(platform::restore(&board, &original));
        // macOS may add types it derives itself (plain UTF-16 text from the RTF), so the saved
        // copy holds at least what was written.
        let saved = platform::snapshot(&board).unwrap();
        assert_eq!(saved.item_count(), 2);
        for name in ["public.rtf", "public.utf8-plain-text", "public.png"] {
            assert!(format!("{saved:?}").contains(name), "{name} missing");
        }

        // Typelite writes its own text, then puts everything back: the same as before.
        assert!(platform::write_text(&board, "dictated", true));
        assert_eq!(platform::read_text(&board).as_deref(), Some("dictated"));
        assert!(platform::restore(&board, &saved));
        assert_eq!(platform::snapshot(&board).unwrap(), saved);
        assert_eq!(platform::read_text(&board).as_deref(), Some("粗體 bold"));
    }

    #[test]
    fn transient_text_carries_the_markers_clipboard_managers_skip() {
        let board = platform::private();
        assert!(platform::write_text(&board, "temporary", true));
        let types = platform::first_item_types(&board);
        assert!(types.contains(&"public.utf8-plain-text".to_string()));
        assert!(types.contains(&"org.nspasteboard.TransientType".to_string()));
        assert!(types.contains(&"org.nspasteboard.AutoGeneratedType".to_string()));

        assert!(platform::write_text(&board, "kept", false));
        assert_eq!(
            platform::first_item_types(&board),
            ["public.utf8-plain-text"]
        );
    }

    #[test]
    fn every_write_moves_the_change_count() {
        let board = platform::private();
        let start = platform::change_count(&board);
        platform::write_text(&board, "a", true);
        let after_write = platform::change_count(&board);
        assert!(after_write > start);
        let empty = platform::snapshot_of(Vec::new());
        assert!(platform::restore(&board, &empty));
        assert!(platform::change_count(&board) > after_write);
        assert_eq!(platform::snapshot(&board).unwrap().item_count(), 0);
        assert_eq!(platform::read_text(&board), None);
    }
}
